// Command generate writes generated.go from ../spec/tools.json.
//
// Run from the go/ directory: go run ./tools/generate
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

type schema struct {
	Type        any                `json:"type"`
	Description string             `json:"description"`
	Enum        []any              `json:"enum"`
	Properties  map[string]*schema `json:"properties"`
	Required    []string           `json:"required"`
	Items       *schema            `json:"items"`
}

type tool struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	InputSchema schema `json:"inputSchema"`
	Annotations struct {
		ReadOnly   bool `json:"readOnlyHint"`
		Idempotent bool `json:"idempotentHint"`
	} `json:"annotations"`
}

var initialisms = map[string]string{"id": "ID", "ids": "IDs", "url": "URL", "uri": "URI", "json": "JSON", "html": "HTML", "api": "API"}

var nonAlnum = regexp.MustCompile(`[^A-Za-z0-9]+`)

func pascal(s string) string {
	var b strings.Builder
	for _, p := range nonAlnum.Split(s, -1) {
		if p == "" {
			continue
		}
		if up, ok := initialisms[strings.ToLower(p)]; ok {
			b.WriteString(up)
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func baseType(s *schema) (string, bool) {
	switch t := s.Type.(type) {
	case string:
		return t, false
	case []any:
		nullable := false
		out := ""
		for _, x := range t {
			if x == "null" {
				nullable = true
			} else if str, ok := x.(string); ok {
				out = str
			}
		}
		return out, nullable
	}
	return "", false
}

var structs = map[string]string{}

// goType returns the Go type; required decides whether scalars are values or pointers.
func goType(s *schema, hint string, required bool) string {
	t, nullable := baseType(s)
	ptr := !required || nullable
	switch t {
	case "string":
		return "string"
	case "integer":
		if ptr {
			return "*int64"
		}
		return "int64"
	case "number":
		if ptr {
			return "*float64"
		}
		return "float64"
	case "boolean":
		if ptr {
			return "*bool"
		}
		return "bool"
	case "array":
		if s.Items == nil {
			return "[]any"
		}
		return "[]" + goType(s.Items, hint+"Item", true)
	case "object":
		if len(s.Properties) == 0 {
			return "map[string]any"
		}
		genStruct(hint, s)
		if ptr {
			return "*" + hint
		}
		return hint
	}
	return "any"
}

func comment(indent, text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	var b strings.Builder
	for _, l := range strings.Split(text, "\n") {
		b.WriteString(indent + "// " + strings.TrimRight(l, " ") + "\n")
	}
	return b.String()
}

func genStruct(name string, s *schema) {
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	keys := make([]string, 0, len(s.Properties))
	for k := range s.Properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", name)
	for _, k := range keys {
		p := s.Properties[k]
		isReq := req[k] && k != "model_name"
		ty := goType(p, name+pascal(k), isReq)
		tag := k
		if !isReq {
			tag += ",omitempty"
		}
		if p.Description != "" || len(p.Enum) > 0 {
			d := p.Description
			if len(p.Enum) > 0 {
				var vals []string
				for _, e := range p.Enum {
					vals = append(vals, fmt.Sprint(e))
				}
				d += " One of: " + strings.Join(vals, ", ") + "."
			}
			b.WriteString(comment("\t", d))
		}
		fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", pascal(k), ty, tag)
	}
	b.WriteString("}\n")
	structs[name] = b.String()
}

func main() {
	raw, err := os.ReadFile(filepath.Join("..", "spec", "tools.json"))
	if err != nil {
		fatal(err)
	}
	var spec struct {
		Tools []tool `json:"tools"`
	}
	if err := json.Unmarshal(raw, &spec); err != nil {
		fatal(err)
	}
	var meta, methods bytes.Buffer
	for _, t := range spec.Tools {
		props := t.InputSchema.Properties
		_, hasCMID := props["client_message_id"]
		_, hasModel := props["model_name"]
		fmt.Fprintf(&meta, "\t%q: {ReadOnly: %v, Idempotent: %v, ClientMessageID: %v, ModelName: %v},\n",
			t.Name, t.Annotations.ReadOnly, t.Annotations.Idempotent, hasCMID, hasModel)
		typeName := pascal(t.Name) + "Args"
		genStruct(typeName, &t.InputSchema)
		structs[typeName] = comment("", typeName+" are the arguments of the "+t.Name+" tool.") + structs[typeName]
		methods.WriteString(comment("", pascal(t.Name)+": "+t.Description))
		fmt.Fprintf(&methods, "func (c *Client) %s(ctx context.Context, args %s) (*ToolResult, error) {\n\treturn c.callStruct(ctx, %q, args)\n}\n\n",
			pascal(t.Name), typeName, t.Name)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/generate from spec/tools.json. DO NOT EDIT.\n\npackage ariousmcp\n\nimport \"context\"\n\n")
	out.WriteString("// toolMeta decides retry safety and automatic arguments per tool.\nvar toolMeta = map[string]ToolMeta{\n")
	out.Write(meta.Bytes())
	out.WriteString("}\n\n")
	names := make([]string, 0, len(structs))
	for n := range structs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		out.WriteString(structs[n])
		out.WriteString("\n")
	}
	out.Write(methods.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		_ = os.WriteFile("generated.go", out.Bytes(), 0o644)
		fatal(err)
	}
	if err := os.WriteFile("generated.go", src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote generated.go (%d tools)\n", len(spec.Tools))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
