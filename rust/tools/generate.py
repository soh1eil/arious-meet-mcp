#!/usr/bin/env python3
"""Generate src/tools.rs from ../spec/tools.json.

Usage: python3 tools/generate.py
"""
import json
import pathlib
import re
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
SPEC = HERE.parent.parent / "spec" / "tools.json"
OUT = HERE.parent / "src" / "tools.rs"
KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use",
    "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final",
    "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
}


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_"))


def ident(s):
    return "r#" + s if s in KEYWORDS else s


CHAT_ACTIONS = ["typing", "upload_photo", "upload_video", "record_voice", "upload_voice",
                "upload_document", "record_video_note", "upload_video_note", "choose_sticker",
                "find_location", "cancel"]


# Tools that gained optional arguments after 0.1.0: the original method keeps its
# signature (no opts parameter) and `<name>_with` takes the options.
KEEP_SIGNATURE = {"send_typing"}


def rtype(sch, owned=True):
    t = sch.get("type")
    if sch.get("enum") == CHAT_ACTIONS:
        return "ChatAction"
    if t == "string":
        return "String"
    if t == "integer":
        return "i64"
    if t == "number":
        return "f64"
    if t == "boolean":
        return "bool"
    if t == "array":
        it = sch.get("items", {})
        return "Vec<%s>" % (rtype(it) if it.get("type") in ("string", "integer", "number", "boolean") else "serde_json::Value")
    return "serde_json::Value"


def doc(text, indent):
    text = (text or "").replace("```", "`")
    out = []
    for line in text.strip().splitlines():
        line = line.strip().replace("[", "\\[").replace("]", "\\]").replace("<", "\\<").replace(">", "\\>")
        out.append(indent + "///" + (" " + line if line else ""))
    return "\n".join(out)


def main():
    tools = json.loads(SPEC.read_text())["tools"]
    o = ["// GENERATED by tools/generate.py from spec/tools.json. DO NOT EDIT.", "",
         "#![allow(clippy::too_many_arguments, clippy::needless_lifetimes)]", "",
         "use serde::Serialize;",
         "use serde_json::{json, Map, Value};", "",
         "use crate::client::{merge_opts, Client, ToolResult, ToolTraits};",
         "use crate::error::Result;", "use crate::types::ChatAction;", ""]
    o.append("/// Names of every tool this SDK was generated for.")
    o.append("pub const TOOL_NAMES: &[&str] = &[")
    for t in tools:
        o.append('    "%s",' % t["name"])
    o.append("];\n")
    o.append("static TRAITS: &[(&str, ToolTraits)] = &[")
    for t in tools:
        s = t["inputSchema"]
        props = s.get("properties", {})
        ann = t.get("annotations", {})
        safe = bool(ann.get("readOnlyHint") or ann.get("idempotentHint"))
        o.append('    ("%s", ToolTraits { has_model_name: %s, requires_model_name: %s, has_client_message_id: %s, safe_to_repeat: %s }),' % (
            t["name"], str("model_name" in props).lower(),
            str("model_name" in s.get("required", [])).lower(),
            str("client_message_id" in props).lower(), str(safe).lower()))
    o.append("];\n")
    o.append("pub(crate) fn traits_for(name: &str) -> Option<ToolTraits> {")
    o.append("    TRAITS.iter().find(|(n, _)| *n == name).map(|(_, t)| *t)")
    o.append("}\n")

    impls = ["impl Client {"]
    for t in tools:
        name = t["name"]
        s = t["inputSchema"]
        props = s.get("properties", {})
        req = [k for k in s.get("required", []) if k != "model_name"]
        req = sorted(req)
        opt = sorted(k for k in props if k not in req)
        sname = pascal(name) + "Opts"
        if opt:
            o.append("/// Optional arguments of `%s`." % name)
            o.append("#[derive(Debug, Clone, Default, Serialize)]")
            o.append("pub struct %s {" % sname)
            for k in opt:
                sch = props[k]
                d = (sch.get("description") or "").strip().replace("\n", " ")
                if sch.get("enum"):
                    d += " One of: %s." % ", ".join(str(e) for e in sch["enum"])
                if d:
                    o.append(doc(d, "    "))
                o.append('    #[serde(skip_serializing_if = "Option::is_none")]')
                o.append("    pub %s: Option<%s>," % (ident(k), rtype(sch)))
            o.append("}\n")
        variants = [(ident(name), True)]
        if name in KEEP_SIGNATURE and opt:
            variants = [(ident(name), False), (ident(name) + "_with", True)]
        for mname, with_opts in variants:
            impls.append(doc(t.get("description", name), "    "))
            impls.append("    ///")
            impls.append("    /// Tool: `%s`." % name)
            params = []
            for k in req:
                sch = props[k]
                tp = rtype(sch)
                params.append("%s: %s" % (ident(k), "impl Into<String>" if tp == "String" else tp))
            if opt and with_opts:
                params.append("opts: %s" % sname)
            impls.append("    pub async fn %s(&self%s) -> Result<ToolResult> {" % (
                mname, "".join(", " + p for p in params)))
            if props:
                impls.append("        let mut args = Map::new();")
                for k in req:
                    tp = rtype(props[k])
                    v = "%s.into()" % ident(k) if tp == "String" else ident(k)
                    impls.append('        args.insert("%s".into(), json!(%s));' % (k, v))
                if opt and with_opts:
                    impls.append("        merge_opts(&mut args, &opts);")
                impls.append('        self.call_tool("%s", Value::Object(args)).await' % name)
            else:
                impls.append('        self.call_tool("%s", Value::Null).await' % name)
            impls.append("    }\n")
    impls.append("}")
    o.extend(impls)
    OUT.write_text("\n".join(o) + "\n")
    try:
        subprocess.run(["cargo", "fmt"], cwd=HERE.parent, check=True)
    except (OSError, subprocess.CalledProcessError):
        print("cargo fmt not available; output left unformatted")
    print("wrote", OUT, len(tools), "tools")


if __name__ == "__main__":
    main()
