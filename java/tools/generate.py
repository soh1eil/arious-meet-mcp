#!/usr/bin/env python3
"""Generate src/main/java/com/ariousmeet/mcp/ToolsBase.java from ../spec/tools.json.

Usage: python3 tools/generate.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SPEC = HERE.parent.parent / "spec" / "tools.json"
OUT = HERE.parent / "src" / "main" / "java" / "com" / "ariousmeet" / "mcp" / "ToolsBase.java"
KEYWORDS = {
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const",
    "continue", "default", "do", "double", "else", "enum", "extends", "final", "finally", "float",
    "for", "goto", "if", "implements", "import", "instanceof", "int", "interface", "long", "native",
    "new", "package", "private", "protected", "public", "return", "short", "static", "strictfp",
    "super", "switch", "synchronized", "this", "throw", "throws", "transient", "try", "void",
    "volatile", "while", "true", "false", "null", "var", "record", "yield", "options",
}
RESERVED_METHODS = {
    "wait", "notify", "notifyAll", "getClass", "hashCode", "equals", "toString", "clone", "finalize",
    "initialize", "listTools", "ping", "close", "notifications", "watchUpdates", "uploadBytes",
    "sendLocalFile", "putBytes", "callTool", "callToolRaw", "setModelName", "builder", "fromEnv",
}


def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pname(s):
    c = camel(s)
    return c + "_" if c in KEYWORDS else c


def jtype(sch):
    t = sch.get("type")
    if t == "string":
        return "String"
    if t == "integer":
        return "long"
    if t == "number":
        return "double"
    if t == "boolean":
        return "boolean"
    if t == "array":
        it = sch.get("items", {}).get("type")
        el = {"string": "String", "integer": "Long", "number": "Double", "boolean": "Boolean"}.get(it, "Object")
        return "List<%s>" % el
    return "Map<String, Object>"


def esc(text):
    text = (text or "").replace("```", "`")
    for a, b in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ("@", "&#64;"), ("{", "&#123;"),
                 ("}", "&#125;"), ("*/", "*&#47;")):
        text = text.replace(a, b)
    return text


def doc(lines, indent="  "):
    out = [indent + "/**"]
    for l in lines:
        out.append(indent + " * " + l if l else indent + " *")
    out.append(indent + " */")
    return out


def main():
    tools = json.loads(SPEC.read_text())["tools"]
    o = ["// GENERATED by tools/generate.py from spec/tools.json. DO NOT EDIT.",
         "package com.ariousmeet.mcp;", "",
         "import java.util.LinkedHashMap;", "import java.util.List;", "import java.util.Map;", "",
         "/** One typed method per server tool. {@link McpClient} extends this. */",
         "public abstract class ToolsBase {",
         "  /** Schema facts the client needs per tool. */",
         "  record Traits(",
         "      boolean hasModelName,",
         "      boolean requiresModelName,",
         "      boolean hasClientMessageId,",
         "      boolean safeToRepeat) {}", "",
         "  private static final Map<String, Traits> TRAITS = new LinkedHashMap<>();", "",
         "  static {"]
    for t in tools:
        s = t["inputSchema"]
        props = s.get("properties", {})
        ann = t.get("annotations", {})
        safe = bool(ann.get("readOnlyHint") or ann.get("idempotentHint"))
        o.append('    TRAITS.put("%s", new Traits(%s, %s, %s, %s));' % (
            t["name"], str("model_name" in props).lower(),
            str("model_name" in s.get("required", [])).lower(),
            str("client_message_id" in props).lower(), str(safe).lower()))
    o.append("  }")
    o.append("")
    o.append("  static Traits traits(String name) {")
    o.append("    return TRAITS.get(name);")
    o.append("  }")
    o.append("")
    o.append("  /** Names of every tool this SDK was generated for. */")
    o.append("  public static java.util.Set<String> toolNames() {")
    o.append("    return java.util.Collections.unmodifiableSet(TRAITS.keySet());")
    o.append("  }")
    o.append("")
    o.append("  /** Calls a tool by name; {@code model_name} and {@code client_message_id} are filled in. */")
    o.append("  public abstract ToolResult callTool(String name, Map<String, Object> arguments);")
    o.append("")
    for t in tools:
        name = t["name"]
        m = camel(name)
        assert m not in RESERVED_METHODS, m
        s = t["inputSchema"]
        props = s.get("properties", {})
        req = sorted(k for k in s.get("required", []) if k != "model_name")
        opt = sorted(k for k in props if k not in req)
        lines = [esc(l.strip()) for l in t.get("description", name).strip().splitlines()]
        lines += ["", "<p>Tool: {@code %s}." % name, ""]
        for k in req:
            d = esc((props[k].get("description") or "").strip().replace("\n", " "))
            lines.append("@param %s %s" % (pname(k), d or "required"))
        if opt:
            lines.append("@param options optional arguments (all nullable), by JSON name:")
            for k in opt:
                sch = props[k]
                d = esc((sch.get("description") or "").strip().replace("\n", " "))
                if sch.get("enum"):
                    d += " One of: %s." % ", ".join(str(e) for e in sch["enum"])
                lines.append("    {@code %s} (%s) %s" % (k, esc(jtype(sch)), d))
        lines.append("@return the tool result; throws {@link McpException.Tool} when the tool answers isError")
        params = ["%s %s" % (jtype(props[k]), pname(k)) for k in req]
        names = [pname(k) for k in req]

        def body(opts_expr, indent="    "):
            b = []
            if props:
                b.append(indent + "Map<String, Object> a = new LinkedHashMap<>();")
                for k in req:
                    b.append(indent + 'a.put("%s", %s);' % (k, pname(k)))
                if opts_expr:
                    b.append(indent + "if (options != null) {")
                    b.append(indent + "  a.putAll(options);")
                    b.append(indent + "}")
                b.append(indent + 'return callTool("%s", a);' % name)
            else:
                b.append(indent + 'return callTool("%s", null);' % name)
            return b

        o.extend(doc(lines))
        o.append("  public ToolResult %s(%s) {" % (m, ", ".join(params)))
        o.extend(body(False))
        o.append("  }")
        o.append("")
        if opt:
            o.extend(doc(["Same as {@link #%s} with optional arguments." % m, "",
                          "@param options optional arguments by JSON name (see the other overload)"]))
            o.append("  public ToolResult %s(%s) {" % (m, ", ".join(params + ["Map<String, Object> options"])))
            o.extend(body(True))
            o.append("  }")
            o.append("")
    o.append("}")
    OUT.write_text("\n".join(o) + "\n")
    print("wrote", OUT, len(tools), "tools")


if __name__ == "__main__":
    main()
