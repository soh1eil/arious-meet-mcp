#!/usr/bin/env python3
"""Generate lib/src/tools.g.dart from ../spec/tools.json.

Usage: python3 tool/generate.py   (from the dart/ folder or anywhere)
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SPEC = HERE.parent.parent / "spec" / "tools.json"
OUT = HERE.parent / "lib" / "src" / "tools.g.dart"
RESERVED = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch", "class", "const",
    "continue", "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export",
    "extends", "extension", "external", "factory", "false", "final", "finally", "for", "get",
    "if", "implements", "import", "in", "interface", "is", "late", "library", "mixin", "new",
    "null", "of", "on", "operator", "part", "required", "rethrow", "return", "set", "static",
    "super", "switch", "sync", "this", "throw", "true", "try", "typedef", "var", "void", "while",
    "with", "yield",
}


def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def ident(s):
    c = camel(s)
    return c + "_" if c in RESERVED else c


CHAT_ACTIONS = ["typing", "upload_photo", "upload_video", "record_voice", "upload_voice",
                "upload_document", "record_video_note", "upload_video_note", "choose_sticker",
                "find_location", "cancel"]


def is_action(sch):
    return sch.get("enum") == CHAT_ACTIONS


def dtype(sch):
    t = sch.get("type")
    if is_action(sch):
        return "ChatAction"
    if t == "string":
        return "String"
    if t == "integer":
        return "int"
    if t == "number":
        return "num"
    if t == "boolean":
        return "bool"
    if t == "array":
        return "List<%s>" % dtype(sch.get("items", {}))
    if t == "object":
        return "Map<String, dynamic>"
    return "Object"


def doc(text, indent="  ", width=76):
    out = []
    for para in (text or "").strip().splitlines():
        para = para.rstrip()
        if not para:
            out.append(indent + "///")
            continue
        words, line = para.split(" "), ""
        for w in words:
            if line and len(indent) + 4 + len(line) + 1 + len(w) > width + 4:
                out.append(indent + "/// " + line)
                line = w
            else:
                line = (line + " " + w).strip() if line else w
        out.append(indent + "/// " + line)
    return "\n".join(out)


def main():
    tools = json.loads(SPEC.read_text())["tools"]
    o = []
    o.append("// GENERATED by tool/generate.py from spec/tools.json. DO NOT EDIT.\n")
    o.append("// ignore_for_file: unnecessary_brace_in_string_interps\n")
    o.append("import 'chat_action.dart';")
    o.append("import 'client.dart';\n")
    o.append("/// Per-tool facts used by [McpClient] (model_name injection, retry safety).")
    o.append("const Map<String, ToolTraits> toolTraits = {")
    for t in tools:
        s = t["inputSchema"]
        props = s.get("properties", {})
        ann = t.get("annotations", {})
        safe = bool(ann.get("readOnlyHint") or ann.get("idempotentHint"))
        o.append("  '%s': ToolTraits(%s)," % (t["name"], ", ".join(
            x for x in [
                "hasModelName: true" if "model_name" in props else "",
                "requiresModelName: true" if "model_name" in s.get("required", []) else "",
                "hasClientMessageId: true" if "client_message_id" in props else "",
                "safeToRepeat: true" if safe else "",
            ] if x)))
    o.append("};\n")
    o.append("/// Names of every tool this SDK was generated for.")
    o.append("const List<String> toolNames = [")
    for t in tools:
        o.append("  '%s'," % t["name"])
    o.append("];\n")
    o.append("/// One typed method per server tool. Required arguments are `required`")
    o.append("/// named parameters; `model_name` is filled from [McpClient.modelName].")
    o.append("extension AriousTools on McpClient {")
    for t in tools:
        s = t["inputSchema"]
        props = s.get("properties", {})
        req = set(s.get("required", []))
        name = t["name"]
        o.append(doc(t.get("description", name)))
        o.append("  ///")
        o.append("  /// Tool: `%s`." % name)
        params = []
        for k in sorted(props, key=lambda k: (k not in req or k == "model_name", k)):
            sch = props[k]
            tp = dtype(sch)
            required = k in req and k != "model_name"
            if sch.get("description") or sch.get("enum"):
                d = (sch.get("description") or "").strip().replace("\n", " ")
                if sch.get("enum"):
                    d += " One of: %s." % ", ".join(str(e) for e in sch["enum"])
                o.append("  ///")
                o.append(doc("[%s] %s" % (ident(k), d)))
            params.append(("required %s %s" if required else "%s? %s") % (tp, ident(k)))
        sig = "{%s}" % ", ".join(params) if params else ""
        m = ident(name)
        o.append("  Future<ToolResult> %s(%s) =>" % (m, sig))
        if props:
            o.append("      callTool('%s', {" % name)
            for k in props:
                if is_action(props[k]):
                    v = ident(k) + (".wire" if k in req else "?.wire")
                else:
                    v = ident(k)
                o.append("        '%s': %s," % (k, v))
            o.append("      });\n")
        else:
            o.append("      callTool('%s');\n" % name)
    o.append("}")
    OUT.write_text("\n".join(o) + "\n")
    print("wrote", OUT, len(tools), "tools")


if __name__ == "__main__":
    main()
