#!/usr/bin/env python3
"""Generate src/AriousMeet.Mcp/Tools.g.cs from ../spec/tools.json.

Usage: python3 tools/generate.py
"""
import json
import pathlib
from xml.sax.saxutils import escape

HERE = pathlib.Path(__file__).resolve().parent
SPEC = HERE.parent.parent / "spec" / "tools.json"
OUT = HERE.parent / "src" / "AriousMeet.Mcp" / "Tools.g.cs"
KEYWORDS = {
    "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class",
    "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event",
    "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
    "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new",
    "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
    "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static",
    "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
    "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
}


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_"))


def camel(s):
    p = pascal(s)
    c = p[:1].lower() + p[1:]
    return "@" + c if c in KEYWORDS else c


CHAT_ACTIONS = ["typing", "upload_photo", "upload_video", "record_voice", "upload_voice",
                "upload_document", "record_video_note", "upload_video_note", "choose_sticker",
                "find_location", "cancel"]


def ctype(sch, nullable):
    t = sch.get("type")
    if sch.get("enum") == CHAT_ACTIONS:
        return "ChatAction" + ("?" if nullable else "")
    value = {"integer": "long", "number": "double", "boolean": "bool"}.get(t)
    if value:
        return value + ("?" if nullable else "")
    if t == "string":
        base = "string"
    elif t == "array":
        it = sch.get("items", {}).get("type")
        el = {"string": "string", "integer": "long", "number": "double", "boolean": "bool"}.get(it, "System.Text.Json.Nodes.JsonNode")
        base = "IReadOnlyList<%s>" % el
    else:
        base = "System.Text.Json.Nodes.JsonNode"
    return base + ("?" if nullable else "")


def doc_lines(text, indent="    "):
    out = []
    for line in (text or "").replace("```", "`").strip().splitlines():
        out.append(indent + "/// " + escape(line.strip()))
    return out


def main():
    tools = json.loads(SPEC.read_text())["tools"]
    o = ["// <auto-generated>",
         "// GENERATED by tools/generate.py from spec/tools.json. DO NOT EDIT.",
         "// </auto-generated>",
         "#nullable enable",
         "using System.Text.Json.Nodes;", "",
         "namespace AriousMeet.Mcp;", ""]
    o.append("internal static class ToolTraitsTable")
    o.append("{")
    o.append("    private static readonly Dictionary<string, ToolTraits> Table = new()")
    o.append("    {")
    for t in tools:
        s = t["inputSchema"]
        props = s.get("properties", {})
        ann = t.get("annotations", {})
        safe = bool(ann.get("readOnlyHint") or ann.get("idempotentHint"))
        o.append('        ["%s"] = new(%s, %s, %s, %s),' % (
            t["name"], str("model_name" in props).lower(),
            str("model_name" in s.get("required", [])).lower(),
            str("client_message_id" in props).lower(), str(safe).lower()))
    o.append("    };")
    o.append("")
    o.append("    public static bool TryGet(string name, out ToolTraits traits) => Table.TryGetValue(name, out traits);")
    o.append("")
    o.append("    public static IReadOnlyCollection<string> Names => Table.Keys;")
    o.append("}")
    o.append("")
    o.append("public sealed partial class McpClient")
    o.append("{")
    o.append("    /// <summary>Names of every tool this SDK was generated for.</summary>")
    o.append("    public static IReadOnlyCollection<string> ToolNames => ToolTraitsTable.Names;")
    o.append("")
    for t in tools:
        name = t["name"]
        s = t["inputSchema"]
        props = s.get("properties", {})
        req = sorted(k for k in s.get("required", []) if k != "model_name")
        opt = sorted(k for k in props if k not in req)
        o.append("    /// <summary>")
        o.extend(doc_lines(t.get("description", name)))
        o.append("    /// </summary>")
        for k in req + opt:
            sch = props[k]
            d = (sch.get("description") or "").strip().replace("\n", " ")
            if sch.get("enum"):
                d += " One of: %s." % ", ".join(str(e) for e in sch["enum"])
            o.append('    /// <param name="%s">%s</param>' % (camel(k).lstrip("@"), escape(d)))
        o.append('    /// <param name="ct">Cancellation token.</param>')
        params = ["%s %s" % (ctype(props[k], False), camel(k)) for k in req]
        params += ["%s %s = null" % (ctype(props[k], True), camel(k)) for k in opt]
        params.append("CancellationToken ct = default")
        o.append("    public Task<ToolResult> %sAsync(%s)" % (pascal(name), ", ".join(params)))
        o.append("    {")
        if props:
            o.append("        var a = new JsonObject();")
            for k in req + opt:
                o.append('        Put(a, "%s", %s);' % (k, camel(k)))
            o.append('        return CallToolAsync("%s", a, true, ct);' % name)
        else:
            o.append('        return CallToolAsync("%s", null, true, ct);' % name)
        o.append("    }")
        o.append("")
    o.append("}")
    OUT.write_text("\n".join(o) + "\n")
    print("wrote", OUT, len(tools), "tools")


if __name__ == "__main__":
    main()
