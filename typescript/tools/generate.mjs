#!/usr/bin/env node
// Generates src/generated.ts from ../spec/tools.json. Run: npm run generate
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(join(here, "..", "..", "spec", "tools.json"), "utf8"));
const out = join(here, "..", "src", "generated.ts");

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const q = (s) => JSON.stringify(s);
const ident = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : q(k));
const doc = (s, indent) =>
  `${indent}/**\n` +
  String(s)
    .replace(/\*\//g, "*\\/")
    .split("\n")
    .map((l) => `${indent} * ${l}`.trimEnd())
    .join("\n") +
  `\n${indent} */\n`;

const CHAT_ACTIONS = [
  "typing",
  "upload_photo",
  "upload_video",
  "record_voice",
  "upload_voice",
  "upload_document",
  "record_video_note",
  "upload_video_note",
  "choose_sticker",
  "find_location",
  "cancel",
];
// Tools whose structured result has a typed model (see src/types.ts).
const RESULT_TYPES = { search_gifs: "SearchGifsResult", send_gif: "SendGifResult" };

function tsType(s, indent) {
  if (!s) return "unknown";
  let t = s.type;
  let nullable = false;
  if (Array.isArray(t)) {
    nullable = t.includes("null");
    t = t.find((x) => x !== "null");
  }
  let r;
  if (s.enum && JSON.stringify(s.enum) === JSON.stringify(CHAT_ACTIONS)) r = "ChatAction";
  else if (s.enum) r = s.enum.map(q).join(" | ");
  else if (t === "string") r = "string";
  else if (t === "integer" || t === "number") r = "number";
  else if (t === "boolean") r = "boolean";
  else if (t === "array") r = `Array<${tsType(s.items, indent)}>`;
  else if (t === "object") r = objType(s, indent);
  else r = "unknown";
  return nullable ? `${r} | null` : r;
}

function objType(s, indent, forceOptional = []) {
  const props = s.properties;
  if (!props) return "Record<string, unknown>";
  const req = new Set(s.required || []);
  const lines = Object.entries(props).map(([k, v]) => {
    const optional = !req.has(k) || forceOptional.includes(k);
    const d = v.description ? doc(v.description, indent + "  ") : "";
    return `${d}${indent}  ${ident(k)}${optional ? "?" : ""}: ${tsType(v, indent + "  ")};`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

const meta = {};
const body = [];
const ifaces = [];
for (const t of spec.tools) {
  const a = t.annotations || {};
  const props = t.inputSchema.properties || {};
  meta[t.name] = {
    readOnly: !!a.readOnlyHint,
    idempotent: !!a.idempotentHint,
    clientMessageId: "client_message_id" in props,
    modelName: "model_name" in props,
  };
  const iname = `${pascal(t.name)}Args`;
  // model_name is filled from the client default, so it is always optional here.
  ifaces.push(
    `${doc(t.description || t.name, "")}export interface ${iname} ${objType(t.inputSchema, "", ["model_name"])}\n`,
  );
  const required = (t.inputSchema.required || []).filter((k) => k !== "model_name");
  const arg = required.length ? `args: ${iname}` : `args: ${iname} = {}`;
  const rt = RESULT_TYPES[t.name] ? `ToolResult<${RESULT_TYPES[t.name]}>` : "ToolResult";
  body.push(
    `${doc(t.description || t.name, "  ")}  ${camel(t.name)}(${arg}): Promise<${rt}> {\n    return this.callTool(${q(t.name)}, args as unknown as Record<string, unknown>);\n  }\n`,
  );
}

const src = `// GENERATED by tools/generate.mjs from spec/tools.json. Do not edit by hand.
/* eslint-disable */
import type { ChatAction, SearchGifsResult, SendGifResult, ToolResult } from "./types.js";

/** Annotations that decide retry safety and automatic arguments. */
export const TOOL_META: Record<string, { readOnly: boolean; idempotent: boolean; clientMessageId: boolean; modelName: boolean }> = ${JSON.stringify(meta, null, 2)};

${ifaces.join("\n")}
/** One typed method per server tool (camelCase of the tool name; argument keys keep the wire names). */
export abstract class GeneratedTools {
  abstract callTool(name: string, args?: Record<string, unknown>): Promise<ToolResult>;

${body.join("\n")}}
`;
writeFileSync(out, src);
console.log(`wrote ${out} (${spec.tools.length} tools)`);
